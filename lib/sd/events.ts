/**
 * A real, dated San Diego fiscal decision for the "What if we had..." retrospective.
 * annualCostM approximates what the decision cost per year within its window versus the
 * alternative that was actually on the table (documented in blurb). ongoingAnnualM is the
 * General Fund room the counterfactual would free TODAY, per year. The replay engine
 * compounds avoided costs forward at the SDCERS assumed return.
 */
export interface SdCounterEvent {
  id: string;
  label: string;
  category: SdEventCategory;
  startYear: number;
  endYear: number;
  annualCostM: number;
  sign: 1 | -1;
  /** Annual General Fund cost that persists today (0 if the bleeding stopped). */
  ongoingAnnualM?: number;
  /** One-line story: what happened and what the alternative was. */
  blurb: string;
  citationId: string;
}

